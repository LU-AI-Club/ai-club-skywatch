"""NFZ-12C: the live runner's zones come from the real FAA file when it exists.

build_live_detector reads airspace.live_path (generated by
scripts/make_faa_airspace.py, not committed). Missing file -> fixture zones and
a WARNING, so the runner still starts. Tests and replay keep the fixture zones.
"""
from __future__ import annotations

import logging
from pathlib import Path

import pytest
import yaml

pytest.importorskip("shapely")
pytest.importorskip("h3")

from air.detectors.no_fly_zone import build_detector, build_live_detector  # noqa: E402
from air.detectors.no_fly_zone.config import DEFAULT_PATH  # noqa: E402

AIRSPACE = Path(__file__).resolve().parents[4] / "air/detectors/no_fly_zone/fixtures/airspace"
FIXTURE_IDS = {"P-901", "TFR-6/1234", "LYNCHBURG-MOA"}


def _config(tmp_path: Path, live_path: object) -> Path:
    raw = yaml.safe_load(DEFAULT_PATH.read_text(encoding="utf-8"))
    raw["airspace"]["live_path"] = live_path
    out = tmp_path / "nfz.yaml"
    out.write_text(yaml.safe_dump(raw), encoding="utf-8")
    return out


def _ids(detector) -> set[str]:
    return {zone.zone_id for zone in detector.zones}


def test_live_runner_uses_the_real_faa_file_when_present(tmp_path: Path) -> None:
    cfg = _config(tmp_path, str(AIRSPACE / "klyh-faa-sample.geojson"))
    ids = _ids(build_live_detector(cfg))
    assert ids and not ids & FIXTURE_IDS


def test_missing_faa_file_falls_back_to_test_zones_and_warns(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    cfg = _config(tmp_path, str(tmp_path / "not-generated.geojson"))
    with caplog.at_level(logging.WARNING, logger="air.detectors.no_fly_zone"):
        detector = build_live_detector(cfg)
    assert _ids(detector) == FIXTURE_IDS
    assert "TEST zones" in caplog.text


def test_no_live_path_configured_means_fixture_zones(tmp_path: Path) -> None:
    assert _ids(build_live_detector(_config(tmp_path, None))) == FIXTURE_IDS


def test_explicit_airspace_path_still_wins(tmp_path: Path) -> None:
    cfg = _config(tmp_path, str(AIRSPACE / "klyh-faa-sample.geojson"))
    detector = build_live_detector(cfg, AIRSPACE / "klyh-150nm.geojson")
    assert _ids(detector) == FIXTURE_IDS


def test_replay_and_tests_never_read_the_live_file(tmp_path: Path) -> None:
    cfg = _config(tmp_path, str(AIRSPACE / "klyh-faa-sample.geojson"))
    assert _ids(build_detector(cfg)) == FIXTURE_IDS
